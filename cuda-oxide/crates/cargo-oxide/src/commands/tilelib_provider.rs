//! The provider form of a tile library: a shared object the Tile IR
//! assembler loads while it compiles a kernel.
//!
//! `cargo oxide tilelib --provider` writes a small `cdylib` crate under the
//! example's target directory, one `define_provider!` over copies of the
//! crate's NVVM IR and descriptions, builds it with the `oxide-tile-provider`
//! runtime, and hands the shared object to `tileiras --preview-create-tile-lib`
//! as the library's only implementation. The runtime answers the assembler's
//! questions from the embedded payload; see that crate for the protocol.
//!
//! ```text
//! <target>/oxide-provider/<stem>/
//! ├── Cargo.toml            cdylib, oxide-tile-provider by path, own [workspace]
//! ├── rust-toolchain.toml   the SIMT pin
//! ├── src/lib.rs            define_provider! { nvvm_ir, descriptions, version }
//! ├── <stem>.ll             copied from the crate
//! └── <stem>.tileexports.json
//! ```

use std::path::{Path, PathBuf};
use std::process::Command;

use oxide_tile_export::DESCRIPTIONS_SUFFIX;
use oxide_tilebc::BytecodeVersion;

use super::*;

/// The line the summary prints once the shared object exists; the path and
/// size follow it.
pub(super) const PROVIDER_BUILT_MARKER: &str = "Tile library provider built:";

/// The variable `oxide-tile-provider-sys` reads the Tile IR compiler's
/// linkage provider header from. The header is not part of this repository.
pub(super) const PROVIDER_INCLUDE_ENV: &str = "TILEIR_LINKAGE_PROVIDER_INCLUDE_DIR";

/// Where the generated crate and its shared object ended up.
pub(super) struct ProviderBuild {
    /// The generated `cdylib` crate.
    pub(super) crate_dir: PathBuf,
    /// `lib<stem>_provider.so`.
    pub(super) shared_object: PathBuf,
}

/// The package name of the generated crate.
pub(super) fn provider_package_name(stem: &str) -> String {
    format!("{stem}-provider")
}

/// The library target name, hence the `lib<name>.so` file name.
pub(super) fn provider_lib_name(stem: &str) -> String {
    format!("{}_provider", stem.replace('-', "_"))
}

/// The generated crate's manifest. Its own `[workspace]` keeps an enclosing
/// workspace from adopting it; the runtime comes from `runtime_path`.
pub(super) fn provider_manifest(stem: &str, runtime_path: &Path) -> String {
    format!(
        "# Generated by `cargo oxide tilelib --provider`; edits are overwritten.\n\
         [package]\n\
         name = \"{}\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         \n\
         [lib]\n\
         name = \"{}\"\n\
         crate-type = [\"cdylib\"]\n\
         \n\
         [dependencies]\n\
         oxide-tile-provider = {{ path = {:?} }}\n\
         \n\
         [workspace]\n",
        provider_package_name(stem),
        provider_lib_name(stem),
        runtime_path.display().to_string(),
    )
}

/// The generated crate's one source file.
pub(super) fn provider_lib_source(
    stem: &str,
    version: BytecodeVersion,
    fma_contraction: bool,
) -> String {
    format!(
        "//! `{stem}` as a Tile IR linkage provider. Generated by `cargo oxide tilelib\n\
         //! --provider`; edits are overwritten.\n\
         oxide_tile_provider::define_provider! {{\n\
         \x20   name: \"{stem}\",\n\
         \x20   descriptions: include_str!(\"../{stem}.{DESCRIPTIONS_SUFFIX}\"),\n\
         \x20   bytecode_version: ({}, {}),\n\
         \x20   nvvm_ir: include_str!(\"../{stem}.ll\"),\n\
         \x20   fma_contraction: {fma_contraction},\n\
         }}\n",
        version.major, version.minor
    )
}

/// Write and build the provider crate for the exports `paths` describe.
pub(super) fn build_provider(
    ctx: &Context,
    example_dir: &Path,
    stem: &str,
    paths: &TileLibraryPaths,
    version: BytecodeVersion,
    verbose: bool,
) -> Result<ProviderBuild, String> {
    if std::env::var_os(PROVIDER_INCLUDE_ENV).is_none_or(|value| value.is_empty()) {
        return Err(format!(
            "the provider runtime binds the Tile IR compiler's linkage provider header, which is \
             not part of this repository; point {PROVIDER_INCLUDE_ENV} at the include directory \
             that holds tile_ir/linkage_provider/LinkageProviderAPI.h"
        ));
    }
    if !ctx.is_workspace {
        return Err(
            "the provider form needs the cuda-oxide workspace: the generated crate depends on \
             crates/oxide-tile-provider by path, and standalone projects do not carry it yet"
                .to_string(),
        );
    }
    let runtime_path = crate::backend::simt_crate_path(&ctx.workspace_root, "oxide-tile-provider");
    if !runtime_path.join("Cargo.toml").is_file() {
        return Err(format!(
            "the provider runtime crate is missing at {}",
            runtime_path.display()
        ));
    }

    let metadata = cargo_metadata(example_dir)?;
    let target_dir = cargo_target_directory(&metadata)?;
    let crate_dir = target_dir.join("oxide-provider").join(stem);
    let src_dir = crate_dir.join("src");
    std::fs::create_dir_all(&src_dir)
        .map_err(|error| format!("could not create {}: {error}", src_dir.display()))?;

    // The crate embeds copies, so it stays self-contained wherever the
    // example's artifacts go next.
    for (from, name) in [
        (&paths.ll, format!("{stem}.ll")),
        (&paths.descriptions, format!("{stem}.{DESCRIPTIONS_SUFFIX}")),
    ] {
        std::fs::copy(from, crate_dir.join(&name)).map_err(|error| {
            format!(
                "could not copy {} into the provider crate: {error}",
                from.display()
            )
        })?;
    }
    let options_path = paths.ll.with_extension("options");
    let options_text = std::fs::read_to_string(&options_path)
        .map_err(|error| format!("could not read {}: {error}", options_path.display()))?;
    let compile_options = oxide_artifacts::ArtifactCompileOptions::from_sidecar_text(&options_text)
        .map_err(|error| {
            format!(
                "invalid compile options at {}: {error}",
                options_path.display()
            )
        })?;

    for (name, text) in [
        ("Cargo.toml", provider_manifest(stem, &runtime_path)),
        ("rust-toolchain.toml", scaffold_rust_toolchain().to_string()),
        (
            "src/lib.rs",
            provider_lib_source(stem, version, compile_options.fma_contraction_enabled()),
        ),
    ] {
        let path = crate_dir.join(name);
        std::fs::write(&path, text)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
    }

    // A host build of an ordinary crate: no device codegen flags, and none
    // of the ambient rustc flags either, which would otherwise fork the
    // runtime's build cache for no reason.
    let build_target_dir = crate_dir.join("target");
    let mut cmd = Command::new("cargo");
    cmd.args(["build", "--release", "--target-dir"])
        .arg(&build_target_dir)
        .current_dir(&crate_dir);
    apply_config_env(&mut cmd, ctx);
    apply_ld_library_path(&mut cmd, ctx);
    cmd.env("CARGO_ENCODED_RUSTFLAGS", "");
    cmd.env_remove("RUSTFLAGS");
    cmd.env_remove("CARGO_BUILD_RUSTFLAGS");
    cmd.env_remove("CARGO_BUILD_TARGET");
    println!();
    println!(
        "Building the provider {} from {}...",
        provider_lib_name(stem),
        crate_dir.display()
    );
    let status = if verbose {
        cmd.status()
            .map_err(|error| format!("could not run cargo: {error}"))?
    } else {
        let output = cmd
            .output()
            .map_err(|error| format!("could not run cargo: {error}"))?;
        if !output.status.success() {
            eprint!("{}", String::from_utf8_lossy(&output.stderr));
        }
        output.status
    };
    if !status.success() {
        return Err(format!(
            "building the provider crate at {} failed with {status}",
            crate_dir.display()
        ));
    }
    let shared_object = build_target_dir
        .join("release")
        .join(format!("lib{}.so", provider_lib_name(stem)));
    if !shared_object.is_file() {
        return Err(format!(
            "the provider build left no {}",
            shared_object.display()
        ));
    }
    Ok(ProviderBuild {
        crate_dir,
        shared_object,
    })
}
