#[cfg(test)]
mod tests {
    use super::*;
    use std::ffi::c_void;

    // Dummy kernel marker for testing
    struct TestKernelMarker;
    impl CudaKernel for TestKernelMarker {
        const PTX_NAME: &'static str = "test_kernel"; // Original function name
    }

    #[repr(C)]
    #[derive(Clone, Copy, Debug, PartialEq)]
    struct TestParams {
        scale: f32,
        bias: i32,
    }

    fn assert_kernel_scalar<T: KernelScalar>() {}

    #[test]
    fn test_ptx_name_lookup() {
        assert_eq!(TestKernelMarker::PTX_NAME, "test_kernel");
    }

    #[test]
    fn test_scalar_wrapper() {
        let s = Scalar(42i32);
        assert_eq!(s.0, 42);
    }

    #[test]
    fn test_kernel_scalar_accepts_copy_argument_kinds() {
        assert_kernel_scalar::<f32>();
        assert_kernel_scalar::<TestParams>();
        assert_kernel_scalar::<*const f32>();
        assert_kernel_scalar::<*mut f32>();

        let offset = 7u32;
        let copy_closure = move |x: u32| x + offset;
        fn assert_value_is_kernel_scalar<T: KernelScalar>(_value: T) {}
        assert_value_is_kernel_scalar(copy_closure);
    }

    #[test]
    fn test_push_kernel_scalar_records_argument_address() {
        let mut args = Vec::new();
        let mut params = TestParams {
            scale: 1.5,
            bias: -2,
        };
        let expected = &mut params as *mut TestParams as *mut c_void;

        push_kernel_scalar(&mut args, &mut params);

        assert_eq!(args, vec![expected]);
        assert_eq!(unsafe { *(args[0] as *const TestParams) }, params);
    }

    #[test]
    fn test_push_kernel_scalar_accepts_copy_closure() {
        let mut args = Vec::new();
        let offset = 3u32;
        let mut copy_closure = move |x: u32| x + offset;
        let expected = &mut copy_closure as *mut _ as *mut c_void;

        push_kernel_scalar(&mut args, &mut copy_closure);

        assert_eq!(args, vec![expected]);
    }

    #[test]
    fn test_push_kernel_scalar_accepts_raw_pointer() {
        let mut args = Vec::new();
        let value = 42f32;
        let mut ptr = &value as *const f32;

        push_kernel_scalar(&mut args, &mut ptr);

        assert_eq!(args.len(), 1);
        assert_eq!(unsafe { *(args[0] as *const *const f32) }, ptr);
    }

    #[repr(align(32))]
    struct AlignedZst;

    #[repr(align(8192))]
    struct AlignedValue {
        _value: u8,
    }

    #[test]
    fn test_kernel_slice_device_ptr_preserves_nonzero_extent_pointer() {
        let ptr: cuda_core::sys::CUdeviceptr = 0x1000;

        assert_eq!(kernel_slice_device_ptr::<u32>(ptr, 4), ptr);
    }

    #[test]
    fn test_kernel_slice_device_ptr_preserves_proven_overalignment() {
        // These are packet metadata only: no address is dereferenced and no
        // device allocation or Rust reference is constructed.
        let ptr = 0x1_0000;
        assert_eq!(kernel_slice_device_ptr::<AlignedValue>(ptr, 2), ptr);
    }

    #[test]
    #[should_panic(expected = "nonempty kernel slice has a null device pointer")]
    fn test_kernel_slice_device_ptr_rejects_nonempty_null() {
        kernel_slice_device_ptr::<u32>(0, 1);
    }

    #[test]
    #[should_panic(expected = "does not satisfy the 8192-byte alignment")]
    fn test_kernel_slice_device_ptr_rejects_insufficient_allocation_alignment() {
        // This address satisfies CUDA's minimum alignment, but not the Rust
        // element type's stronger requirement. Reject before making a packet.
        kernel_slice_device_ptr::<AlignedValue>(0x1000, 1);
    }

    #[test]
    fn test_kernel_slice_device_ptr_empty_overaligned_value_needs_no_allocation() {
        assert_eq!(kernel_slice_device_ptr::<AlignedValue>(0, 0), 8192);
    }

    #[test]
    fn test_kernel_slice_device_ptr_normalizes_empty_slice() {
        let ptr = kernel_slice_device_ptr::<u32>(0, 0);
        let align = std::mem::align_of::<u32>() as cuda_core::sys::CUdeviceptr;

        assert_ne!(ptr, 0);
        assert_eq!(ptr, align);
        assert_eq!(ptr % align, 0);
    }

    #[test]
    fn test_kernel_slice_device_ptr_normalizes_overaligned_zst() {
        let ptr = kernel_slice_device_ptr::<AlignedZst>(0, 8);
        let align = std::mem::align_of::<AlignedZst>() as cuda_core::sys::CUdeviceptr;

        assert_ne!(ptr, 0);
        assert_eq!(ptr, align);
        assert_eq!(ptr % align, 0);
    }

    #[test]
    fn test_push_kernel_device_slice_records_pointer_and_len() {
        let mut args = Vec::new();
        let mut ptr: cuda_core::sys::CUdeviceptr = 0xfeed_beefu64;
        let mut len = 1024u64;

        push_kernel_device_slice(&mut args, &mut ptr, &mut len);

        assert_eq!(args.len(), 2);
        assert_eq!(
            unsafe { *(args[0] as *const cuda_core::sys::CUdeviceptr) },
            ptr
        );
        assert_eq!(unsafe { *(args[1] as *const u64) }, len);
    }
}
