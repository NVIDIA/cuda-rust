use crate::render::all_outputs;
use crate::resolve::resolve;
use crate::util::{check_contents, pretty_json, rustfmt_source, sha256_bytes, write_if_changed};
use anyhow::Result;
use serde::Deserialize;
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

const MANAGED_GENERATED_ROOTS: &[&str] = &[
    "crates/cuda-intrinsics/src/generated",
    "crates/cuda-device/src/generated",
    "crates/cuda-oxide-codegen/src",
    "crates/dialect-nvvm/src/ops/generated",
    "crates/mir-importer/src/translator/terminator/intrinsics",
    "crates/mir-importer/src",
    "crates/mir-lower/src/convert",
    "crates/rustc-codegen-cuda/src",
    "intrinsics/probes",
];
const GENERATED_MARKER: &[u8] = b"@generated by cuda-intrinsics-gen";

/// Just the shard list from `intrinsics/overlay.toml`.
///
/// `resolve` parses that manifest for its own purposes, but only the shard
/// names are needed to reconcile it against the directory, and this crate
/// already reads it once per run without keeping the list on the catalog.
#[derive(Deserialize)]
struct OverlayShardIndex {
    #[serde(default)]
    shards: Vec<String>,
}

/// Overlay files present on disk that `intrinsics/overlay.toml` does not list.
///
/// The manifest is an explicit index: `read_overlay` reads the shards it names
/// and nothing else, so a family file added to `intrinsics/overlay/` and left
/// out of `shards` is never read at all. Its intrinsics simply do not exist,
/// and every gate agrees -- the resolved catalog matches the committed one
/// because the file was never an input, so `check` reports the outputs current
/// and the ABI ledger sees nothing missing.
///
/// The opposite mistake is already caught. Dropping a listed shard makes the
/// ledger fail with "active ABI ledger entry ... has no overlay record",
/// because the entry outlives the record. Only the unlisted-file direction is
/// silent, and it is the likelier slip: adding the file is the visible half of
/// the work, editing the index the forgettable half.
///
/// This is the input-side twin of [`stale_generated_outputs`], which
/// reconciles the same way for managed outputs.
///
/// The walk recurses because the manifest grammar does:
/// `validate_overlay_shard_path` accepts nested paths such as
/// `overlay/sub/foo.toml`, so a flat listing would miss exactly the files
/// this check exists to catch whenever one sits in a subdirectory.
fn unindexed_overlay_shards(repo_root: &Path) -> Result<Vec<String>> {
    let manifest_path = repo_root.join("intrinsics/overlay.toml");
    let manifest = fs::read(&manifest_path)
        .map_err(|error| anyhow::anyhow!("read {}: {error}", manifest_path.display()))?;
    let index: OverlayShardIndex = toml::from_slice(&manifest)
        .map_err(|error| anyhow::anyhow!("parse {}: {error}", manifest_path.display()))?;

    // A manifest that parsed to nothing would make every file on disk look
    // unindexed, which reads as a broken run rather than a real finding.
    anyhow::ensure!(
        !index.shards.is_empty(),
        "{} lists no shards; refusing to report every overlay file as unindexed",
        manifest_path.display()
    );
    let listed: BTreeSet<&str> = index.shards.iter().map(String::as_str).collect();

    let intrinsics_root = repo_root.join("intrinsics");
    let overlay_dir = intrinsics_root.join("overlay");
    let mut on_disk = Vec::new();
    collect_overlay_toml_files(&intrinsics_root, &overlay_dir, &mut on_disk)?;

    // Same reasoning in the other direction: a walk that stopped matching
    // would report a clean reconciliation from an empty comparison.
    anyhow::ensure!(
        !on_disk.is_empty(),
        "found no .toml files under {}; refusing to report a clean result",
        overlay_dir.display()
    );

    let mut unindexed: Vec<String> = on_disk
        .into_iter()
        .filter(|relative| !listed.contains(relative.as_str()))
        .collect();
    unindexed.sort();
    Ok(unindexed)
}

/// Collects every `.toml` under `directory`, recursing into subdirectories,
/// as paths relative to `intrinsics/` (the form `shards` entries use).
fn collect_overlay_toml_files(
    intrinsics_root: &Path,
    directory: &Path,
    found: &mut Vec<String>,
) -> Result<()> {
    for entry in fs::read_dir(directory)
        .map_err(|error| anyhow::anyhow!("read {}: {error}", directory.display()))?
    {
        let entry = entry?;
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            collect_overlay_toml_files(intrinsics_root, &path, found)?;
        } else if file_type.is_file()
            && path.extension().and_then(|extension| extension.to_str()) == Some("toml")
        {
            let Some(relative) = path
                .strip_prefix(intrinsics_root)
                .ok()
                .and_then(|relative| relative.to_str())
            else {
                continue;
            };
            found.push(relative.to_string());
        }
    }
    Ok(())
}

pub fn run(repo_root: &Path, check: bool) -> Result<()> {
    let unindexed = unindexed_overlay_shards(repo_root)?;
    if !unindexed.is_empty() {
        anyhow::bail!(
            "intrinsics/overlay.toml does not list {} overlay file(s), so they are \
             never read and their intrinsics do not exist: {}. Add them to `shards` \
             (the list is sorted).",
            unindexed.len(),
            unindexed.join(", ")
        );
    }

    let catalog = resolve(repo_root)?;
    let catalog_json = pretty_json(&catalog)?;
    let catalog_hash = sha256_bytes(catalog_json.as_bytes());
    let mut outputs = all_outputs(&catalog, catalog_json, &catalog_hash)?;
    let expected: BTreeSet<PathBuf> = outputs.keys().cloned().collect();
    for (path, contents) in &mut outputs {
        if path.extension().and_then(|extension| extension.to_str()) == Some("rs") {
            *contents = rustfmt_source(contents)?;
        }
    }
    let mut changed = 0usize;
    for (relative, contents) in outputs {
        let path = repo_root.join(relative);
        if check {
            check_contents(&path, &contents)?;
        } else if write_if_changed(&path, &contents)? {
            changed += 1;
            println!("wrote {}", path.display());
        }
    }
    for relative in stale_generated_outputs(repo_root, &expected)? {
        let path = repo_root.join(&relative);
        if check {
            anyhow::bail!(
                "stale managed generated output remains at {}; run cuda-intrinsics-gen generate",
                path.display()
            );
        } else {
            fs::remove_file(&path)?;
            changed += 1;
            println!("removed stale {}", path.display());
        }
    }
    if check {
        println!("generated intrinsic outputs are current");
    } else if changed == 0 {
        println!("generated intrinsic outputs were already current");
    } else {
        println!("updated {changed} generated intrinsic outputs");
    }
    Ok(())
}

fn stale_generated_outputs(repo_root: &Path, expected: &BTreeSet<PathBuf>) -> Result<Vec<PathBuf>> {
    let mut stale = Vec::new();
    for relative_root in MANAGED_GENERATED_ROOTS {
        let root = repo_root.join(relative_root);
        if root.is_dir() {
            collect_stale_generated(repo_root, &root, expected, &mut stale)?;
        }
    }
    stale.sort();
    stale.dedup();
    Ok(stale)
}

fn collect_stale_generated(
    repo_root: &Path,
    directory: &Path,
    expected: &BTreeSet<PathBuf>,
    stale: &mut Vec<PathBuf>,
) -> Result<()> {
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            collect_stale_generated(repo_root, &path, expected, stale)?;
        } else if file_type.is_file() {
            let bytes = fs::read(&path)?;
            if bytes
                .windows(GENERATED_MARKER.len())
                .any(|window| window == GENERATED_MARKER)
            {
                let relative = path.strip_prefix(repo_root)?.to_path_buf();
                if !expected.contains(&relative) {
                    stale.push(relative);
                }
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    #[test]
    fn unexpected_marker_bearing_file_is_stale() {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let root = std::env::temp_dir().join(format!(
            "cuda-intrinsics-gen-stale-{}-{unique}",
            std::process::id()
        ));
        let directory = root.join("intrinsics/probes");
        fs::create_dir_all(&directory).unwrap();
        fs::write(
            directory.join("removed.ll"),
            "; @generated by cuda-intrinsics-gen test\n",
        )
        .unwrap();

        let stale = stale_generated_outputs(&root, &BTreeSet::new()).unwrap();
        assert_eq!(stale, [PathBuf::from("intrinsics/probes/removed.ll")]);
        fs::remove_dir_all(root).unwrap();
    }

    fn overlay_fixture(label: &str, shards: &[&str], on_disk: &[&str]) -> PathBuf {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let root = std::env::temp_dir().join(format!(
            "cuda-intrinsics-gen-{label}-{}-{unique}",
            std::process::id()
        ));
        let overlay = root.join("intrinsics/overlay");
        fs::create_dir_all(&overlay).unwrap();
        let listed = shards
            .iter()
            .map(|name| format!("    \"overlay/{name}\",\n"))
            .collect::<String>();
        fs::write(
            root.join("intrinsics/overlay.toml"),
            format!("shards = [\n{listed}]\n"),
        )
        .unwrap();
        for name in on_disk {
            let path = overlay.join(name);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, "# fixture\n").unwrap();
        }
        root
    }

    /// A family file added to `intrinsics/overlay/` but left out of `shards`
    /// is never read, and nothing else notices: the resolved catalog matches
    /// the committed one because the file was never an input.
    #[test]
    fn overlay_file_missing_from_the_index_is_reported() {
        let root = overlay_fixture(
            "unindexed",
            &["listed.toml"],
            &["listed.toml", "forgotten.toml"],
        );
        let unindexed = unindexed_overlay_shards(&root).unwrap();
        assert_eq!(unindexed, ["overlay/forgotten.toml"]);
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn fully_indexed_overlay_directory_reports_nothing() {
        let root = overlay_fixture("indexed", &["a.toml", "b.toml"], &["a.toml", "b.toml"]);
        assert!(unindexed_overlay_shards(&root).unwrap().is_empty());
        fs::remove_dir_all(root).unwrap();
    }

    /// The manifest grammar accepts nested shard paths, so the walk must
    /// descend: a forgotten file is no less forgotten for sitting in a
    /// subdirectory.
    #[test]
    fn overlay_file_in_a_subdirectory_is_still_reconciled() {
        let root = overlay_fixture(
            "nested",
            &["listed.toml"],
            &["listed.toml", "sub/forgotten.toml"],
        );
        let unindexed = unindexed_overlay_shards(&root).unwrap();
        assert_eq!(unindexed, ["overlay/sub/forgotten.toml"]);
        fs::remove_dir_all(root).unwrap();
    }

    /// A fully nested but fully indexed layout is a valid tree: the nested
    /// files must count as seen so the empty-directory refusal does not fire
    /// on it.
    #[test]
    fn nested_indexed_layout_is_not_mistaken_for_an_empty_directory() {
        let root = overlay_fixture("nested-indexed", &["sub/a.toml"], &["sub/a.toml"]);
        assert!(unindexed_overlay_shards(&root).unwrap().is_empty());
        fs::remove_dir_all(root).unwrap();
    }

    /// Both self-tests: an index that parsed to nothing would make every file
    /// look unindexed, and a directory read that found nothing would report a
    /// clean reconciliation from an empty comparison.
    #[test]
    fn empty_index_or_empty_directory_refuses_to_answer() {
        let empty_index = overlay_fixture("empty-index", &[], &["a.toml"]);
        let error = unindexed_overlay_shards(&empty_index)
            .unwrap_err()
            .to_string();
        assert!(error.contains("lists no shards"), "{error}");
        fs::remove_dir_all(empty_index).unwrap();

        let empty_dir = overlay_fixture("empty-dir", &["a.toml"], &[]);
        let error = unindexed_overlay_shards(&empty_dir)
            .unwrap_err()
            .to_string();
        assert!(error.contains("found no .toml files"), "{error}");
        fs::remove_dir_all(empty_dir).unwrap();
    }
}
