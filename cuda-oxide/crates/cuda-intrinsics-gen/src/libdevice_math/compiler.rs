//! Render the shared dispatch used by the importer, lowerer, and collector.

use super::{Link, Mapping};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// Polymorphic fast-math binary intrinsics without libm aliases or libdevice ABIs.
pub(super) const FAST: &[(&str, &str, &str)] = &[
    ("FaddFast", "CALLEE_FADD_FAST", "fadd_fast"),
    ("FsubFast", "CALLEE_FSUB_FAST", "fsub_fast"),
    ("FmulFast", "CALLEE_FMUL_FAST", "fmul_fast"),
    ("FdivFast", "CALLEE_FDIV_FAST", "fdiv_fast"),
    ("FremFast", "CALLEE_FREM_FAST", "frem_fast"),
];

/// Render the Rust source for `crates/dialect-mir/src/generated/libdevice_math.rs`.
pub(super) fn render(rows: &[Mapping]) -> String {
    let mut out = String::from(
        "/*\n * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n * SPDX-License-Identifier: Apache-2.0\n */\n\n// @generated by cuda-intrinsics-gen from overlay/libdevice_math.toml. DO NOT EDIT.\n\n",
    );
    let mut constants = BTreeMap::new();
    let mut variants: BTreeMap<&str, BTreeMap<&str, &Mapping>> = BTreeMap::new();
    let mut paths = BTreeMap::new();
    let mut exports = BTreeMap::new();
    for row in rows {
        let Some(variant) = row.variant.as_deref() else {
            continue;
        };
        let constant = row.constant.as_deref().unwrap();
        constants.insert(constant, &row.placeholders[0]);
        variants.entry(variant).or_default().insert(&row.width, row);
        for path in &row.paths {
            paths.insert(path, variant);
        }
        if let Some(libm) = &row.libm {
            exports.insert(libm, variant);
        }
    }
    for (constant, suffix) in constants {
        writeln!(out, "/// Internal math placeholder generated from the libdevice shard.\npub const {constant}: &str = placeholder!({suffix:?});").unwrap();
    }
    out.push_str("\n/// Shared math identity. Semantic expansions remain in the importer and lowerer.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum RustFloatMathIntrinsic {\n");
    for variant in variants
        .keys()
        .copied()
        .chain(FAST.iter().map(|entry| entry.0))
    {
        writeln!(
            out,
            "/// Generated math identity for `{variant}`.\n{variant},"
        )
        .unwrap();
    }
    out.push_str("}\n\n/// Every generated floating-point math intrinsic identity.\npub const ALL_FLOAT_MATH_INTRINSICS: &[RustFloatMathIntrinsic] = &[\n");
    for variant in variants
        .keys()
        .copied()
        .chain(FAST.iter().map(|entry| entry.0))
    {
        writeln!(out, "RustFloatMathIntrinsic::{variant},").unwrap();
    }
    out.push_str(
        "];\n\n\
/// Whether a math placeholder needs libdevice under the selected backend.\n\
#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
pub enum MathLink {\n\
    /// Requires libdevice on both the LLVM NVPTX and libNVVM backends.\n\
    Always,\n\
    /// Uses a native LLVM intrinsic on NVPTX and libdevice only under libNVVM.\n\
    Libnvvm,\n\
    /// Expands inline in LLVM IR and never links a libdevice symbol.\n\
    Never,\n\
}\n\n\
/// Scalar types in a Rust math placeholder signature.\n\
#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
pub enum MathScalarType {\n\
    /// 32-bit IEEE-754 binary floating-point (`f32`).\n\
    F32,\n\
    /// 64-bit IEEE-754 binary floating-point (`f64`).\n\
    F64,\n\
    /// 32-bit signed integer (`i32`).\n\
    I32,\n\
}\n\n\
/// Lowering strategy for a [`RustFloatMathIntrinsic`] placeholder call.\n\
#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
pub enum RustFloatMathLowering {\n\
    /// Lower to a direct scalar libdevice or LLVM intrinsic call.\n\
    ScalarCall { symbol: &'static str, arity: usize },\n\
    /// Call the libdevice Bessel j1 entry and normalize +-inf to +0.0.\n\
    BesselJ1 { symbol: &'static str },\n\
    /// Adapt libdevice frexp's out-parameter ABI and non-finite exponent contract.\n\
    Frexp { symbol: &'static str },\n\
    /// Adapt libdevice modf's out-parameter ABI into a two-float tuple.\n\
    Modf { symbol: &'static str },\n\
    /// Adapt libdevice remquo's out-parameter ABI and zero invalid quotients.\n\
    Remquo { symbol: &'static str },\n\
    /// Compose `(log(abs(gamma(x))), signgam)` from scalar libdevice calls.\n\
    LgammaR,\n\
    /// Expand `sincos`/`sincosf` into paired scalar `sin` and `cos` calls.\n\
    Sincos { is_f64: bool },\n\
    /// Expand NaN-ignoring `fmin`/`fmax` (`*_nsz`) to ordered compare and select.\n\
    MinMaxNsz { is_max: bool },\n\
    /// Expand IEEE-754-2019 `fmaximum*`/`fminimum*` with signed-zero tie-breaking.\n\
    IeeeMinMax { is_max: bool, propagate_nan: bool },\n\
    /// Lower `f*_fast` intrinsics to LLVM float binary ops with fast-math flags.\n\
    FastBinop,\n\
}\n\n\
impl RustFloatMathIntrinsic {\n",
    );

    out.push_str("/// Return the lowering strategy generated from the libdevice math shard.\npub const fn lowering(self) -> RustFloatMathLowering { match self {\n");
    for (variant, widths) in &variants {
        let arm = lowering_arm(variant, widths.values().next().unwrap());
        writeln!(out, "Self::{variant} => {arm},").unwrap();
    }
    for (variant, _, _) in FAST {
        writeln!(out, "Self::{variant} => RustFloatMathLowering::FastBinop,").unwrap();
    }
    out.push_str("} }\n\n/// Recognize exact core, cmath, or libm compiler paths.\npub fn from_core_path(name: &str) -> Option<Self> { match name {\n");
    for (path, variant) in paths {
        writeln!(out, "{path:?} => Some(Self::{variant}),").unwrap();
    }
    for (variant, _, name) in FAST {
        writeln!(
            out,
            "\"core::intrinsics::{name}\" | \"std::intrinsics::{name}\" => Some(Self::{variant}),"
        )
        .unwrap();
    }
    out.push_str("_ => Self::from_libm_path(name),\n} }\n\n/// Resolve aliases only within the libm crate namespace.\npub fn from_libm_path(name: &str) -> Option<Self> {\nif !is_libm_path(name) { return None; }\nmatch name.rsplit(\"::\").next().unwrap_or(name) {\n");
    for (export, variant) in exports {
        writeln!(out, "{export:?} => Some(Self::{variant}),").unwrap();
    }
    out.push_str("_ => None,\n} }\n\n/// Return the placeholder emitted for this math identity.\npub fn placeholder_callee(self) -> &'static str { match self {\n");
    for (variant, widths) in &variants {
        writeln!(
            out,
            "Self::{variant} => {},",
            widths.values().next().unwrap().constant.as_deref().unwrap()
        )
        .unwrap();
    }
    for (variant, constant, _) in FAST {
        writeln!(out, "Self::{variant} => {constant},").unwrap();
    }
    out.push_str("} }\n\n/// Recover an identity from an exact known placeholder.\npub fn from_placeholder_callee(callee: &str) -> Option<Self> { match callee {\n");
    for (variant, widths) in &variants {
        writeln!(
            out,
            "{} => Some(Self::{variant}),",
            widths.values().next().unwrap().constant.as_deref().unwrap()
        )
        .unwrap();
    }
    for (variant, constant, _) in FAST {
        writeln!(out, "{constant} => Some(Self::{variant}),").unwrap();
    }
    out.push_str("_ => None,\n} }\n\n/// Operand count of the Rust placeholder, before C ABI adaptation.\npub fn arg_count(self) -> usize { match self {\n");
    for (variant, widths) in &variants {
        let signature = &widths.values().next().unwrap().signature;
        let arity = signature.split(" -> ").next().unwrap().matches(',').count() + 1;
        writeln!(out, "Self::{variant} => {arity},").unwrap();
    }
    for (variant, _, _) in FAST {
        writeln!(out, "Self::{variant} => 2,").unwrap();
    }
    out.push_str("} }\n\n/// Typed scalar ABI before libdevice lookup; tuples and fast arithmetic use handwritten lowerings.\npub fn scalar_signature(self, is_f64: bool) -> Option<(&'static [MathScalarType], MathScalarType)> { match self {\n");
    for (variant, widths) in &variants {
        if widths.len() == 2 {
            writeln!(
                out,
                "Self::{variant} => if is_f64 {{ {} }} else {{ {} }},",
                scalar_signature(widths["f64"]),
                scalar_signature(widths["f32"])
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "Self::{variant} => {},",
                scalar_signature(widths.values().next().unwrap())
            )
            .unwrap();
        }
    }
    for (variant, _, _) in FAST {
        writeln!(out, "Self::{variant} => None,").unwrap();
    }
    out.push_str("} }\n\n/// Classify libdevice linking without accepting unknown placeholder prefixes.\npub fn link_requirement(self) -> MathLink { match self {\n");
    for (variant, widths) in &variants {
        let link = match widths.values().next().unwrap().link {
            Link::Always => "Always",
            Link::Libnvvm => "Libnvvm",
            Link::Never => "Never",
        };
        writeln!(out, "Self::{variant} => MathLink::{link},").unwrap();
    }
    for (variant, _, _) in FAST {
        writeln!(out, "Self::{variant} => MathLink::Never,").unwrap();
    }
    out.push_str("} }\n");
    for (method, llvm) in [("libdevice_symbol", false), ("llvm_symbol", true)] {
        writeln!(out, "\n/// Resolve the symbol; only generic placeholders consult the concrete width.\npub fn {method}(self, is_f64: bool) -> Option<&'static str> {{ match self {{").unwrap();
        for (variant, widths) in &variants {
            if widths.len() == 2 {
                writeln!(
                    out,
                    "Self::{variant} => if is_f64 {{ {:?} }} else {{ {:?} }},",
                    symbol(widths["f64"], llvm),
                    symbol(widths["f32"], llvm)
                )
                .unwrap();
            } else {
                writeln!(
                    out,
                    "Self::{variant} => {:?},",
                    symbol(widths.values().next().unwrap(), llvm)
                )
                .unwrap();
            }
        }
        for (variant, _, _) in FAST {
            writeln!(out, "Self::{variant} => None,").unwrap();
        }
        out.push_str("} }\n");
    }
    out.push_str("}\n\n/// Whether the path belongs to the libm crate, rather than a user namespace.\npub fn is_libm_path(name: &str) -> bool { name.split(\"::\").next() == Some(\"libm\") }\n\n/// Exact std shims intercepted before the collector's forbidden-std guard.\npub fn is_intrinsic_lowered_cmath_shim(name: &str) -> bool { matches!(name,\n");
    let cmath: BTreeSet<_> = rows.iter().filter_map(|row| row.cmath.as_deref()).collect();
    if cmath.is_empty() {
        out.push_str("_ if false");
    } else {
        out.push_str(
            &cmath
                .into_iter()
                .map(|path| format!("{path:?}"))
                .collect::<Vec<_>>()
                .join(" | "),
        );
    }
    out.push_str(") }\n\n/// Sincos retains its importer tuple expansion into two scalar placeholders.\npub fn libm_sincos_lowering(name: &str) -> Option<RustFloatMathLowering> {\nif !is_libm_path(name) { return None; }\nmatch name.rsplit(\"::\").next().unwrap_or(name) {\n");
    for row in rows
        .iter()
        .filter(|row| row.lowering.as_deref() == Some("handwritten:emit_sincos"))
    {
        writeln!(
            out,
            "{:?} => Some(RustFloatMathLowering::Sincos {{ is_f64: {} }}),",
            row.libm.as_deref().unwrap(),
            row.width == "f64"
        )
        .unwrap();
    }
    out.push_str("_ => None,\n} }\n\n/// Return whether `name` is the `f64` (`Some(true)`) or `f32` (`Some(false)`) `libm::sincos` entry.\npub fn libm_sincos_is_f64(name: &str) -> Option<bool> {\nmatch libm_sincos_lowering(name) {\nSome(RustFloatMathLowering::Sincos { is_f64 }) => Some(is_f64),\n_ => None,\n} }\n");
    out
}

/// Render the `RustFloatMathLowering` match arm for one shard-backed variant.
fn lowering_arm(variant: &str, row: &Mapping) -> String {
    let arity = row
        .signature
        .split(" -> ")
        .next()
        .unwrap()
        .matches(',')
        .count()
        + 1;
    match row.lowering.as_deref() {
        None => {
            let symbol = row.libdevice.as_deref().unwrap();
            format!("RustFloatMathLowering::ScalarCall {{ symbol: {symbol:?}, arity: {arity} }}")
        }
        Some("handwritten:lower_bessel_j1") => {
            let symbol = row.libdevice.as_deref().unwrap();
            format!("RustFloatMathLowering::BesselJ1 {{ symbol: {symbol:?} }}")
        }
        Some("handwritten:emit_frexp") => {
            let symbol = row.libdevice.as_deref().unwrap();
            format!("RustFloatMathLowering::Frexp {{ symbol: {symbol:?} }}")
        }
        Some("handwritten:emit_modf") => {
            let symbol = row.libdevice.as_deref().unwrap();
            format!("RustFloatMathLowering::Modf {{ symbol: {symbol:?} }}")
        }
        Some("handwritten:emit_remquo") => {
            let symbol = row.libdevice.as_deref().unwrap();
            format!("RustFloatMathLowering::Remquo {{ symbol: {symbol:?} }}")
        }
        Some("handwritten:emit_lgamma_r") => "RustFloatMathLowering::LgammaR".into(),
        Some("handwritten:lower_float_minmax_nsz") => {
            let is_max = variant.starts_with("Max");
            format!("RustFloatMathLowering::MinMaxNsz {{ is_max: {is_max} }}")
        }
        Some("handwritten:lower_float_ieee_minmax") => {
            let is_max = variant.starts_with("Maximum");
            let propagate_nan = !variant.contains("Number");
            format!(
                "RustFloatMathLowering::IeeeMinMax {{ is_max: {is_max}, propagate_nan: {propagate_nan} }}"
            )
        }
        Some(other) => unreachable!("validated handwritten math lowering: {other}"),
    }
}

/// Select the LLVM intrinsic symbol or libdevice symbol for a mapping row.
fn symbol(row: &Mapping, llvm: bool) -> Option<&str> {
    if llvm {
        row.llvm.as_deref()
    } else {
        row.libdevice.as_deref()
    }
}

/// Render the `Option<(&'static [MathScalarType], MathScalarType)>` literal for a row.
fn scalar_signature(row: &Mapping) -> String {
    let (arguments, result) = row.signature.split_once(" -> ").unwrap();
    if result.starts_with('(') {
        return "None".into();
    }
    let scalar = |name: &str| match name.trim() {
        "f32" => "MathScalarType::F32",
        "f64" => "MathScalarType::F64",
        "i32" => "MathScalarType::I32",
        _ => unreachable!("validated math signature"),
    };
    let arguments = arguments
        .trim_start_matches('(')
        .trim_end_matches(')')
        .split(',')
        .map(scalar)
        .collect::<Vec<_>>()
        .join(", ");
    format!("Some((&[{arguments}], {}))", scalar(result))
}
