//! Render the Markdown reference and compiler dispatch for libdevice math.

use super::{Mapping, compiler};
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::PathBuf;

/// Render the generated Markdown reference and compiler dispatch files.
pub(super) fn outputs(rows: &[Mapping], bitcode_hash: &str) -> BTreeMap<PathBuf, String> {
    let exports = rows.iter().filter(|row| row.libm.is_some()).count();
    let mut reference = format!(
        "<!-- SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved. -->\n<!-- SPDX-License-Identifier: Apache-2.0 -->\n<!-- @generated by cuda-intrinsics-gen. DO NOT EDIT. -->\n\n# Compiler math mappings\n\n{exports} mapped f32/f64 libm exports, plus core-only compiler routes.\n\nThe same shard generates compiler dispatch, placeholder constants, symbol lookup,\noperand counts, cmath interception, and libdevice link requirements. Handwritten\nsemantic expansions remain responsible for sincos, frexp, modf, remquo, lgamma_r, legacy min/max, C23 min/max, j1 infinity correction, and fast binops.\n\nLibdevice bitcode SHA-256: `{bitcode_hash}`.\n\n`libnvvm` links only on that backend; `always` links on both; `never` uses\na handwritten expansion. Aliases are separate exports sharing a mapping.\n\n"
    );
    let headers = [
        "libm export",
        "Rust signature",
        "libdevice symbol",
        "LLVM NVPTX alternative",
        "Handwritten lowering",
        "Linking",
    ];
    let table_rows: Vec<[String; 6]> = rows
        .iter()
        .map(|row| {
            [
                code(row.libm.as_deref()),
                format!("`{}`", row.signature),
                code(row.libdevice.as_deref()),
                code(row.llvm.as_deref()),
                code(row.lowering.as_deref()),
                format!("`{}`", row.link.as_str()),
            ]
        })
        .collect();
    let mut widths = headers.map(str::len);
    for cells in &table_rows {
        for (width, cell) in widths.iter_mut().zip(cells) {
            *width = (*width).max(cell.len());
        }
    }
    write_row(&mut reference, &headers, &widths);
    let separators = widths.map(|width| "-".repeat(width));
    let separator_refs: [&str; 6] = std::array::from_fn(|i| separators[i].as_str());
    write_row(&mut reference, &separator_refs, &widths);
    for cells in &table_rows {
        let cell_refs: [&str; 6] = std::array::from_fn(|i| cells[i].as_str());
        write_row(&mut reference, &cell_refs, &widths);
    }
    BTreeMap::from([
        (PathBuf::from("intrinsics/libdevice-math.md"), reference),
        (
            PathBuf::from("crates/dialect-mir/src/generated/libdevice_math.rs"),
            compiler::render(rows),
        ),
    ])
}

/// Append one padded Markdown table row with aligned column separators.
fn write_row(out: &mut String, cells: &[&str; 6], widths: &[usize; 6]) {
    out.push('|');
    for (cell, width) in cells.iter().zip(widths) {
        write!(out, " {cell:<width$} |").unwrap();
    }
    out.push('\n');
}

/// Format an optional cell value as inline Markdown code or an empty string.
fn code(value: Option<&str>) -> String {
    value.map(|text| format!("`{text}`")).unwrap_or_default()
}
